import os
import sys
import argparse
import numpy as np
from sklearn.metrics import classification_report, confusion_matrix

# ensure scripts dir and repo root on sys.path
scripts_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if scripts_dir not in sys.path:
    sys.path.insert(0, scripts_dir)
if repo_root not in sys.path:
    sys.path.insert(1, repo_root)

from evaluation.evaluate import CLASS_NAMES


def merge_results(stage1_dir, stage2_dir, save_dir):
    s1_preds = np.load(os.path.join(stage1_dir, "stage1_preds.npy"))
    s1_probs = np.load(os.path.join(stage1_dir, "stage1_probs.npy"))
    y_true = np.load(os.path.join(stage1_dir, "y_true.npy"))

    # stage2 may store both indices and preds in its folder
    s2_indices_path = os.path.join(stage2_dir, "stage2_indices.npy")
    if os.path.exists(s2_indices_path):
        indices = np.load(s2_indices_path)
    else:
        # fallback: try stage2 saved indices
        indices = np.load(os.path.join(stage2_dir, "stage2_indices.npy"))

    s2_preds = np.load(os.path.join(stage2_dir, "stage2_preds.npy"))

    final = s1_preds.copy()

    # IMPORTANT: Stage-2 is a binary classifier (Real vs AI Edited) and does NOT
    # predict the 'AI Generated' class. Therefore we MUST NEVER apply Stage-2 to
    # samples which Stage-1 already labeled as 'AI Generated' (class 1). Doing so
    # would overwrite valid Stage-1 AI-Generated predictions with a forced binary
    # label and destroy AI-Generated recall.

    # For safety, when merging only override Stage-1 predictions for indices that
    # were both sent to Stage-2 and were NOT predicted as AI Generated by Stage-1.
    for i_local, idx in enumerate(indices):
        s1 = int(s1_preds[idx])
        # If Stage-1 marked this sample as AI Generated, never overwrite it.
        if s1 == 1:
            continue
        s2 = int(s2_preds[i_local])
        final[idx] = 0 if s2 == 0 else 2

    os.makedirs(save_dir, exist_ok=True)
    out_path = os.path.join(save_dir, "y_pred_final.npy")
    np.save(out_path, final)

    present_labels = sorted(set(y_true))
    present_names = [CLASS_NAMES[i] for i in present_labels]

    print("\nClassification report (final cascade):")
    print(classification_report(y_true, final, labels=present_labels, target_names=present_names, digits=4))
    print("Confusion matrix:")
    print(confusion_matrix(y_true, final, labels=present_labels))
    print(f"Saved final predictions to: {out_path}")


def main():
    parser = argparse.ArgumentParser(description="Merge Stage-1 and Stage-2 cascade results")
    parser.add_argument('--stage1_dir', default="results/cascade_stage1")
    parser.add_argument('--stage2_dir', default="results/cascade_stage2")
    parser.add_argument('--save_dir', default="results/cascade_final")
    args = parser.parse_args()
    merge_results(args.stage1_dir, args.stage2_dir, args.save_dir)


if __name__ == "__main__":
    main()
